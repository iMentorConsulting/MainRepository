/** Map customer nationality string → language code */
export function nationalityToLang(nationality) {
  if (!nationality) return 'en'
  const n = nationality.toLowerCase().trim()
  const GREEK = ['gr', 'grc', 'greek', 'greece', 'ελλάδα', 'ελλας', 'ελληνας', 'ελληνίδα', 'έλληνας']
  const GERMAN = ['de', 'deu', 'german', 'germany', 'deutsch', 'deutschland', 'at', 'aut', 'austria', 'österreich', 'ch', 'che', 'switzerland', 'schweiz']
  const FRENCH = ['fr', 'fra', 'french', 'france', 'français', 'be', 'bel', 'belgium', 'belgique']
  if (GREEK.includes(n)) return 'el'
  if (GERMAN.includes(n)) return 'de'
  if (FRENCH.includes(n)) return 'fr'
  return 'en'
}

export function useLang(initial = 'en') {
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('guest_lang') : null
  return stored || initial
}
